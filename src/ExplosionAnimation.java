/**
 * src/ExplosionAnimation.java
 *
 * Utility class that loads and manages the frames and timing of an explosion animation
 * from an animated GIF file. Provides methods to load the animation, retrieve the appropriate
 * frame for a given elapsed time, and handle errors during loading.
 * 
 * Holds the decoded frames and per-frame durations of a GIF explosion animation.
 * Provides methods to load an animation from a GIF file and to retrieve the correct
 * frame for a given elapsed time during playback.
 *
 * This class was written to work around Java's limited built-in support for animated GIFs, which
 * does not expose per-frame durations through standard APIs.
 *
 * Sources used: (my sheer apologies for whoever has to check all these links)
 * https://stackoverflow.com/questions/2935232/show-animated-gif for animated GIF frame extraction.
 * https://docs.oracle.com/javase/8/docs/api/javax/imageio/ImageIO.html for ImageIO reader usage.
 * https://docs.oracle.com/javase/8/docs/api/javax/imageio/stream/ImageInputStream.html for image stream handling.
 * https://docs.oracle.com/javase/8/docs/api/javax/imageio/metadata/IIOMetadata.html for GIF frame metadata.
 * https://docs.oracle.com/javase/8/docs/api/org/w3c/dom/Node.html for DOM metadata traversal.
 * https://docs.oracle.com/javase/8/docs/api/java/util/Optional.html for Optional usage.
 * Claude Sonnet 4.6 for support with GIF reading and resource loading, along with comments.
 *
 * @since 2026-04-02
 */
import java.awt.image.BufferedImage;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import javax.imageio.*;
import javax.imageio.stream.ImageInputStream;
import org.w3c.dom.*;

public class ExplosionAnimation {
    private static final long NANOS_PER_CENTISECOND = 10_000_000L;

    private final BufferedImage[] frames;
    private final long[] frameEndNanos;
    private final long totalDurationNanos;

    /**
     * Constructs an ExplosionAnimation with pre-decoded frames and timing data.
     *
     * @param frames the decoded animation frames in display order
     * @param frameEndNanos cumulative nanosecond end times for each frame
     * @param totalDurationNanos total animation duration in nanoseconds
     */
    public ExplosionAnimation(BufferedImage[] frames, long[] frameEndNanos, long totalDurationNanos) {
        this.frames = frames;
        this.frameEndNanos = frameEndNanos;
        this.totalDurationNanos = totalDurationNanos;
    }

    /**
     * Loads an explosion animation from the specified path. Attempts to read the file as a GIF,
     * extracting all frames and their per-frame durations. Returns an empty animation if loading fails.
     *
     * Partially generated by Claude Sonnet 4.6; originally implemented with a static image loader,
     * then extended to support animated GIFs.
     *
     * Sources used:
     * https://stackoverflow.com/questions/2935232/show-animated-gif for animated GIF frame extraction.
     * https://docs.oracle.com/javase/8/docs/api/javax/imageio/ImageIO.html for ImageIO reader usage.
     * Claude Sonnet 4.6 for GIF reading and resource loading support.
     *
     * @param path the resource path or file path to load the explosion animation from;
     *     tried first as a classpath resource, then as a filesystem path
     * @return an ExplosionAnimation containing the loaded frames and timing, or an empty
     *     animation if loading fails
     */
    public static ExplosionAnimation load(String path) {
        try (ImageInputStream imageStream = openImageStream(path)) {
            if (imageStream == null) {
                System.err.println("Explosion animation not found: " + path);
                return empty();
            }

            /**
             * ImageIO.getImageReaders returns an iterator; we only need the first reader.
             *
             * Sources used:
             * https://docs.oracle.com/javase/8/docs/api/javax/imageio/ImageIO.html for ImageIO reader usage.
             * https://docs.oracle.com/javase/8/docs/api/java/util/Optional.html for Optional usage.
             * Claude Sonnet 4.6 for the logic to handle the case where no reader is available,
             *      which can occur if the file is not a valid GIF or if GIF support is not present in the Java runtime.
             *      In this case, we log an error and return an empty animation instead of throwing an exception.
             */
            Optional<ImageReader> maybeReader = ImageIO.getImageReaders(imageStream).hasNext()
                ? Optional.of(ImageIO.getImageReaders(imageStream).next())
                : Optional.empty();
            if (maybeReader.isEmpty()) {
                System.err.println("No GIF reader available for: " + path);
                return empty();
            }

            ImageReader reader = maybeReader.get();
            try {
                reader.setInput(imageStream, false, false);
                int frameCount = reader.getNumImages(true);
                if (frameCount <= 0) {
                    return empty();
                }

                List<BufferedImage> loadedFrames = new ArrayList<>(frameCount);
                long[] frameEnds = new long[frameCount];
                long elapsedNanos = 0L;

                for (int i = 0; i < frameCount; i++) {
                    BufferedImage frame = reader.read(i);
                    loadedFrames.add(frame);

                    long frameDuration = extractFrameDurationNanos(reader, i);
                    elapsedNanos += frameDuration;
                    frameEnds[i] = elapsedNanos;
                }

                if (elapsedNanos <= 0L) {
                    elapsedNanos = 1L;
                    frameEnds[frameEnds.length - 1] = elapsedNanos;
                }

                return new ExplosionAnimation(
                    loadedFrames.toArray(BufferedImage[]::new),
                    frameEnds,
                    elapsedNanos
                );
            } finally {
                reader.dispose();
            }
        } catch (IOException e) {
            System.err.println("Failed to load explosion animation '" + path + "': " + e.getMessage());
            return empty();
        }
    }

    /**
     * Returns whether this animation contains at least one frame.
     *
     * @return true if frames were loaded successfully, false if the animation is empty
     */
    public boolean hasFrames() {
        return frames.length > 0;
    }

    /**
     * Returns the total playback duration of the animation in nanoseconds.
     *
     * @return sum of all frame durations in nanoseconds
     */
    public long getTotalDurationNanos() {
        return totalDurationNanos;
    }

    /**
     * Returns the appropriate frame for the given elapsed time in nanoseconds. Returns the last
     * frame if elapsed time exceeds the total duration. Returns null if there are no frames.
     *
     * @param elapsedNanos elapsed time in nanoseconds since the start of the animation
     * @return the BufferedImage frame at the given time, or null if no frames exist
     */
    public BufferedImage getFrameAt(long elapsedNanos) {
        if (frames.length == 0) {
            return null;
        }

        if (elapsedNanos <= 0L) {
            return frames[0];
        }

        for (int i = 0; i < frameEndNanos.length; i++) {
            if (elapsedNanos < frameEndNanos[i]) {
                return frames[i];
            }
        }

        return frames[frames.length - 1];
    }

    private static ExplosionAnimation empty() {
        return new ExplosionAnimation(new BufferedImage[0], new long[0], 0L);
    }

    /**
     * Opens an ImageInputStream for the given path. Tries the classpath first, then the
     * filesystem, including a fallback into a "resources/" subdirectory.
     *
     * Sources used:
     * https://docs.oracle.com/javase/8/docs/api/javax/imageio/stream/ImageInputStream.html for image stream handling.
     * Claude Sonnet 4.6 for classpath and filesystem fallback logic.
     *
     * @param path the resource path or file path to load
     * @return an ImageInputStream for the path, or null if the resource cannot be found
     * @throws IOException if an I/O error occurs while opening the stream
     */
    private static ImageInputStream openImageStream(String path) throws IOException {
        InputStream resourceStream = Main.class.getClassLoader().getResourceAsStream(path);
        if (resourceStream != null) {
            return ImageIO.createImageInputStream(resourceStream);
        }

        Path imagePath = Path.of(path);
        if (!Files.exists(imagePath)) {
            imagePath = Path.of("resources", Path.of(path).getFileName().toString());
        }

        if (!Files.exists(imagePath)) {
            return null;
        }

        return ImageIO.createImageInputStream(imagePath.toFile());
    }

    /**
     * Extracts the frame duration in nanoseconds from GIF metadata. Reads the
     * "GraphicControlExtension" node and its "delayTime" attribute, which is in centiseconds.
     * Defaults to 10 centiseconds (100 ms) if the delay is missing or zero.
     *
     * Sources used:
     * https://docs.oracle.com/javase/8/docs/api/javax/imageio/metadata/IIOMetadata.html for GIF frame metadata.
     * Claude Sonnet 4.6 for metadata extraction logic.
     *
     * @param reader the ImageReader positioned at the desired frame
     * @param frameIndex the index of the frame to extract the duration for
     * @return the duration of the frame in nanoseconds
     * @throws IOException if an error occurs while reading the metadata
     */
    private static long extractFrameDurationNanos(ImageReader reader, int frameIndex) throws IOException {
        Node root = reader.getImageMetadata(frameIndex).getAsTree("javax_imageio_gif_image_1.0");
        Node graphicsControl = findChild(root, "GraphicControlExtension");
        if (graphicsControl == null) {
            return 10L * NANOS_PER_CENTISECOND;
        }

        NamedNodeMap attributes = graphicsControl.getAttributes();
        Node delayNode = attributes == null ? null : attributes.getNamedItem("delayTime");
        int delayCentiseconds = delayNode == null ? 10 : Integer.parseInt(delayNode.getNodeValue());
        if (delayCentiseconds <= 0) {
            delayCentiseconds = 1;
        }
        return delayCentiseconds * NANOS_PER_CENTISECOND;
    }

    /**
     * Recursively searches the metadata DOM tree for a node with the specified name.
     * Returns the first matching node found, or null if no match exists.
     *
     * Sources used:
     * https://docs.oracle.com/javase/8/docs/api/org/w3c/dom/Node.html for DOM metadata traversal.
     * Claude Sonnet 4.6 for recursive DOM traversal logic.
     *
     * @param root the root node to start the search from
     * @param nodeName the name of the node to search for
     * @return the first Node with the specified name, or null if not found
     */
    private static Node findChild(Node root, String nodeName) {
        if (root == null) {
            return null;
        }

        if (Objects.equals(root.getNodeName(), nodeName)) {
            return root;
        }

        Node child = root.getFirstChild();
        while (child != null) {
            Node found = findChild(child, nodeName);
            if (found != null) {
                return found;
            }
            child = child.getNextSibling();
        }
        return null;
    }
}
